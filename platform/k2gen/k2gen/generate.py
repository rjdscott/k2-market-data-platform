def scaffold(root: Path, domain: str, name: str) -> list[Path]:
    """Write contracts/<domain>/<name>/: product.yaml and one contract. Raises SystemExit on bad input."""
    contracts = root / "contracts"
    domains = yaml.safe_load((contracts / "domains.yaml").read_text())["domains"]
    slug = json.loads((contracts / "schema" / "k2.schema.json").read_text())["$defs"]["slug"]["pattern"]
    if domain not in domains:
        raise SystemExit(f"k2gen new: {domain} is not a domain in contracts/domains.yaml: {', '.join(domains)}")
    if not re.fullmatch(slug, name):
        raise SystemExit(f"k2gen new: {name} is not a product name ({slug})")
    pdir = contracts / domain / name
    if pdir.exists():
        raise SystemExit(f"k2gen new: {pdir.relative_to(root)} already exists")
    # The scaffold's layer: a source-aligned product lands what a source sent, a consumer-aligned one derives.
    layer = "bronze" if domains[domain]["kind"] == "source-aligned" else "gold"
    short = name.replace("-", "_")
    fields = dict(name=name, domain=domain, owner=domains[domain]["owner"], kind=domains[domain]["kind"])
    fields |= dict(layer=layer, short=short, table=f"{layer}.{short}")
    pdir.mkdir(parents=True)
    written = [pdir / "product.yaml", pdir / f"{fields['table']}{SUFFIX}"]
    written[0].write_text(PRODUCT.format(**fields))
    written[1].write_text(CONTRACT.format(**fields))
    return written
