"""k2gen generate and k2gen new: files written from the contracts (ADR-032).

`generate` runs only on a tree `validate` passes. It renders every output in
memory, deletes the directories it owns, then writes them again in sorted
order, so two runs are byte-identical and a deleted contract leaves nothing:

    docker/lake/ddl/generated/            DDL for contracts with inline columns (owned)
    docker/lake/generated/retention.json  snapshot expiry in days, per table
    docs/products/                        a page per product and the index (owned)

and, from contracts/domains.yaml, one fence per domain (ADR-044):

    docker/lake/generated/warehouses.txt  the Lakekeeper warehouses init-lake.sh creates
    docker/trino/etc/catalog/<fence>.properties   a writable Trino catalog per domain
    docker/trino/test/local/<fence>.properties    its twin on a local metastore, for make test-trino
    docker/trino/etc/rules.json           each domain's writer writes only its own catalog

A catalog file is the generator's if it starts with the generated header; those are
deleted and written again, so a removed domain takes its catalog with it, and the
hand-written `lake.properties` beside them is never touched.

`new` scaffolds contracts/<domain>/<name>/: a descriptor and one contract for a
table lake.sql does not create, so its columns are inline and `generate` writes
its DDL. The scaffold passes `validate` as written.
"""

import json
import re
import shutil
from pathlib import Path
from typing import Any

import yaml

from k2gen import ddl
from k2gen.cli import LAKE_SQL, SUFFIX, fence

GENERATED_DDL = "docker/lake/ddl/generated"
RETENTION = "docker/lake/generated/retention.json"
PAGES = "docs/products"
OWNED = (GENERATED_DDL, PAGES)
WAREHOUSES = "docker/lake/generated/warehouses.txt"
TRINO_RULES = "docker/trino/etc/rules.json"
CATALOGS = "docker/trino/etc/catalog"
TEST_CATALOGS = "docker/trino/test/local"
HEADER = "Generated by `k2gen generate` from contracts/. Do not edit: change the contract, then `make generate`."
ADR = "docs/adr/ADR-032-odcs-contracts-and-k2gen.md"
# What every table in lake.sql declares (its header says why: copy-on-write, append-only).
TBLPROPERTIES = (
    ("format-version", "2"),
    ("write.format.default", "parquet"),
    ("write.parquet.compression-codec", "zstd"),
    ("write.distribution-mode", "hash"),
    ("write.delete.mode", "copy-on-write"),
    ("write.update.mode", "copy-on-write"),
    ("write.merge.mode", "copy-on-write"),
)

Contract = tuple[str, dict[str, Any], dict[str, Any]]  # path from the root, contract, custom properties


def _text(text: str) -> str:
    """Prose for a page: whitespace folded, and no em-dash, which check-docs gate (h) refuses."""
    return re.sub(r"\s*\u2014\s*", ": ", " ".join(text.split()))


def _cell(text: str) -> str:
    return _text(text).replace("|", "\\|")


def _code(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items) or "none"


def _sql(text: str) -> str:
    return "'" + " ".join(text.split()).replace("'", "''") + "'"


def _diagram(product: dict[str, Any], tables: dict[str, Contract]) -> list[str]:
    """Inputs on the left, the product's outputs in a box, one edge per upstream a contract names."""
    inputs = sorted(i.get("table") or i["external"] for i in product["inputs"])
    ids = {name: f"n{n}" for n, name in enumerate([*inputs, *product["outputs"]])}
    return [
        "```mermaid",
        "flowchart LR",
        *[f'  {ids[i]}["{i}"]' for i in inputs],
        f'  subgraph product ["{product["name"]}"]',
        *[f'    {ids[t]}["{t}"]' for t in product["outputs"]],
        "  end",
        *[f"  {ids[up]} --> {ids[t]}" for t in product["outputs"] for up in tables[t][2]["upstreams"]],
        "```",
    ]


def _columns(doc: dict[str, Any], lake: dict[str, ddl.Table]) -> list[str]:
    schema = doc["schema"][0]
    if "properties" in schema:
        rows = [(c["name"], c["physicalType"] + (" NOT NULL" if c.get("required") else ""), c["description"]) for c in schema["properties"]]
    else:
        # A measured number belongs to its dated source, not to a generated page: lake.sql keeps it.
        rows = [(c.name, c.type, re.sub(r" \(measured [^)]*\)", "", c.comment)) for c in lake[schema["physicalName"]].schema]
    return ["| Column | Type | Description |", "|---|---|---|", *[f"| `{n}` | `{t}` | {_cell(d)} |" for n, t, d in rows]]


def _page(product: dict[str, Any], tables: dict[str, Contract], lake: dict[str, ddl.Table], home: dict[str, str]) -> str:
    key = f"{product['domain']}/{product['name']}"
    up = "../../.."  # docs/products/<domain>/ to the repository root
    lines = [
        f"<!-- {HEADER} -->",
        f"# {product['name']}",
        "",
        _text(product["purpose"]),
        "",
        "| | |",
        "|---|---|",
        f"| Domain | [{product['domain']}](../README.md#{product['domain']}) |",
        f"| Owner | `{product['owner']}` |",
        f"| Kind | {product['kind']} |",
        f"| Lifecycle | {product['lifecycle']} |",
        f"| Descriptor | [`contracts/{key}/product.yaml`]({up}/contracts/{key}/product.yaml) |",
        "",
        "## Inputs and outputs",
        "",
        *_diagram(product, tables),
        "",
    ]
    if product["inputs"]:
        lines += ["| Input | What it is |", "|---|---|"]
        for i in product["inputs"]:
            if "table" in i:
                lines.append(f"| `{i['table']}` | an output of [{home[i['table']]}](../{home[i['table']]}.md) |")
            else:
                lines.append(f"| `{i['external']}` | external source, classified {i['classification']}. {_cell(i['description'])} |")
    else:
        lines.append("No inputs declared.")
    if product["consumers"]:
        lines += ["", "Known readers outside the contracts:", "", *[f"- {_text(c)}" for c in product["consumers"]]]
    else:
        lines += ["", "Known readers outside the contracts: none declared."]
    for table in product["outputs"]:
        path, doc, props = tables[table]
        if "properties" in doc["schema"][0]:
            source = f"[`{GENERATED_DDL}/{table}.sql`]({up}/{GENERATED_DDL}/{table}.sql)"
        else:
            source = f"[`{LAKE_SQL}`]({up}/{LAKE_SQL})"
        lines += [
            "",
            f"## {table}",
            "",
            _text(doc["description"]["purpose"]),
            "",
            "| | |",
            "|---|---|",
            f"| Classification | {props['classification']} |",
            f"| Entitlement | {props['entitlement']} |",
            f"| Retention | snapshots expire after {props['retention']} days; no row is deleted ([ADR-032]({up}/{ADR})) |",
            f"| Partitioning | {_code(props['partitioning'])} |",
            f"| Sort | {_code(props['sort'])} |",
            f"| Schedule | {_code([props['schedule']] if props['schedule'] else [])} |",
            f"| Reads | {_code(props['upstreams'])} |",
            f"| Contract | [`{Path(path).name}`]({up}/{path}), version {doc['version']} |",
            f"| DDL | {source} |",
            "",
            *_columns(doc, lake),
        ]
    return "\n".join(lines) + "\n"


def _index(domains: dict[str, Any], products: list[dict[str, Any]]) -> str:
    lines = [
        f"<!-- {HEADER} -->",
        "# Data products",
        "",
        "One page per data product, by domain, written from its descriptor and contracts under",
        "[`contracts/`](../../contracts/domains.yaml). Each page names the owner, what the product",
        "reads and writes, and every output's classification, retention and columns.",
        "How a product is added: [the golden path](../development/golden-path.md).",
    ]
    for name, domain in domains.items():
        lines += ["", f"## {name}", "", f"Owner `{domain['owner']}`, {domain['kind']}. {_text(domain['description'])}", ""]
        mine = [p for p in products if p["domain"] == name]
        if not mine:
            lines.append("No product yet.")
            continue
        lines += ["| Product | Lifecycle | Outputs |", "|---|---|---|"]
        lines += [f"| [{p['name']}]({name}/{p['name']}.md) | {p['lifecycle']} | {_code(p['outputs'])} |" for p in mine]
    return "\n".join(lines) + "\n"


def _ddl_readme(tables: list[str]) -> str:
    listed = "\n".join(f"- `{t}.sql`" for t in tables) or "None today: every contract references `lake.sql`."
    return f"""# Generated Iceberg DDL

{HEADER}

`k2gen generate` deletes this directory and writes it again on every run. It holds one
`<namespace>.<table>.sql` per contract with inline columns, which is how a new product's
table is declared. `docker/lake/apply_ddl.py` applies them in name order after `lake.sql`,
which stays the DDL of record for every table it creates
([ADR-032](../../../../{ADR})).

{listed}
"""


def _table_ddl(path: str, doc: dict[str, Any], props: dict[str, Any]) -> str:
    """CREATE TABLE in lake.sql's own shape, so ddl.parse reads it back and apply_ddl splits it."""
    schema = doc["schema"][0]
    table, cols = schema["physicalName"], schema["properties"]
    width = max(len(c["name"]) for c in cols)
    null = {True: " NOT NULL", False: ""}
    defs = [f"    {c['name']:<{width}} {c['physicalType']}{null[c.get('required', False)]} COMMENT {_sql(c['description'])}" for c in cols]
    tblprops = [f"    '{k}' = '{v}'" for k, v in TBLPROPERTIES] + [f"    'comment' = {_sql(doc['description']['purpose'])}"]
    out = [f"-- {HEADER}", f"-- Source: {path}", f"CREATE TABLE IF NOT EXISTS lake.{table} (", ",\n".join(defs), ")", "USING iceberg"]
    if props["partitioning"]:
        out.append(f"PARTITIONED BY ({', '.join(props['partitioning'])})")
    out += ["TBLPROPERTIES (", ",\n".join(tblprops), ");"]
    if props["sort"]:
        out += ["", f"ALTER TABLE lake.{table}", f"    WRITE DISTRIBUTED BY PARTITION LOCALLY ORDERED BY {', '.join(props['sort'])};"]
    return "\n".join(out) + "\n"


