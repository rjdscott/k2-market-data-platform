def _catalog(domain: str, spec: dict[str, Any], local: bool) -> str:
    name = fence(domain)
    head = (
        f"# {HEADER}\n"
        f"# Domain {domain} ({spec['owner']}): warehouse {name}, key prefix warehouse/{name}.\n"
        f"# Only dbt_{name} creates, changes or drops its tables and rows (rules.json); table\n"
        f"# procedures are not fenced per user (ADR-044).\n"
    )
    body = (_CATALOG_LOCAL if local else _CATALOG_REST).format(name=name, common=_CATALOG_COMMON)
    return head + body


def _rules(domains: dict[str, Any]) -> str:
    """File-based rules, first match wins in each list (ADR-044).

    Every catalog is `all` at the catalog level, and the fence sits in the schema and
    table rules: a domain's writer owns its own catalog's schemas and tables, and every
    user, that writer included, may only read (`SELECT`, `GRANT_SELECT`) everything
    else. Two reasons it is not a read-only catalog rule. A definer view in one domain
    over `lake` or another domain is readable by others only if its owner has `all` on
    the base table's catalog (`checkCanCreateViewWithSelectFromColumns`); and `lake`
    needs no rule to stay unwritten, because its connector is read-only.
    """
    names = sorted(fence(d) for d in domains)
    write = ["SELECT", "INSERT", "DELETE", "UPDATE", "OWNERSHIP", "GRANT_SELECT"]
    # The Iceberg connector's two retention floors are session properties with no lower
    # bound: anyone who may set them can expire every snapshot or orphan-clean a table at
    # 0s (probed on k2-trino, 2026-11-25). Nobody may, a domain's writer in its own
    # catalog included: snapshot maintenance belongs to the platform, not to SQL users.
    floors = "expire_snapshots_min_retention|remove_orphan_files_min_retention"
    rules = {
        "catalogs": [
            {"catalog": "system", "allow": "read-only"},
            {"catalog": "|".join(["lake", *names]), "allow": "all"},
        ],
        "schemas": [{"user": f"dbt_{n}", "catalog": n, "owner": True} for n in names] + [{"owner": False}],
        "tables": [{"user": f"dbt_{n}", "catalog": n, "privileges": write} for n in names]
        + [{"privileges": ["SELECT", "GRANT_SELECT"]}],
        "catalog_session_properties": [{"property": floors, "allow": False}, {"allow": True}],
        # Everyone executes; a user views and kills only its own queries, which Trino
        # always allows. Without this list any user could read and kill anyone's.
        "queries": [{"allow": ["execute"]}],
        "system_information": [{"allow": ["read"]}],
    }
    return json.dumps(rules, indent=2) + "\n"


def _warehouses(domains: dict[str, Any]) -> str:
    return f"# {HEADER}\n# One per domain in contracts/domains.yaml; docker/lake/init-lake.sh creates each after the lake.\n" + "".join(
        f"{fence(d)}\n" for d in sorted(domains)
    )


# lake.sql's Spark types as Trino reads them through the Iceberg connector (verified on
# k2-trino, 2026-11-25: DESCRIBE lake.gold.trades). A type a mart reads first must be added.
_TRINO_TYPES = {"STRING": "varchar", "BIGINT": "bigint", "INT": "integer", "BOOLEAN": "boolean", "TIMESTAMP": "timestamp(6) with time zone"}
_PERIODS = {"min": "minute", "h": "hour", "d": "day"}  # ODCS units, as k2.schema.json allows them
# The uniqueness check covers the newest 6 hours by the table's time partition, not the
# whole table. On k2-trino, 2026-11-25, the check over all of gold.trades, and over its last
# 2 days, failed with "Query exceeded per-node memory limit of 844.80MB" (Trino's default at
# a 2816M heap); over its last 6 hours it took 2.6 s. The command, with the window varied, is
# in dbt/README.md. The whole table is the nightly Spark audit's (duplicate_identifiers,
# docker/lake/maintenance.py).
_RECENT = "interval '6' hour"
_TIME_TRANSFORMS = ("hours", "days", "months", "years")


def _trino_type(spark: str) -> str:
    base = spark.removesuffix(" NOT NULL")
    if re.fullmatch(r"DECIMAL\(\d+,\d+\)", base):
        return base.lower()
    if base not in _TRINO_TYPES:
        raise ValueError(f"no Trino type for {spark} in k2gen/generate.py _TRINO_TYPES: a mart reads it, add it")
    return _TRINO_TYPES[base]


def _yaml(doc: Any) -> str:
    return f"# {HEADER}\n" + yaml.safe_dump(doc, sort_keys=False, width=1000, allow_unicode=True)


def _dbt_sources(products: list[dict[str, Any]], tables: dict[str, Contract], lake: dict[str, ddl.Table]) -> str:
    """One dbt source per lake namespace a mart reads, each table with its columns and checks."""
    readers: dict[str, list[str]] = {}
    for p in products:
        for mart in p.get("marts", []):
            for table in mart["reads"]:
                readers.setdefault(table, []).append(mart["table"])
    sources: dict[str, list[dict[str, Any]]] = {}
    for table in sorted(readers):
        path, doc, props = tables[table]
        namespace, name = table.split(".")
        schema = doc["schema"][0]
        if "properties" in schema:
            columns = [(c["name"], c["physicalType"], c["description"]) for c in schema["properties"]]
            identifier: tuple[str, ...] = ()
        else:
            columns = [(c.name, c.type, re.sub(r" \(measured [^)]*\)", "", c.comment)) for c in lake[table].schema]
            identifier = lake[table].identifier
        recent = [ddl.column_of(f) for f in props["partitioning"] if f.split("(")[0] in _TIME_TRANSFORMS][:1]
        entry: dict[str, Any] = {
            "name": name,
            "description": _text(doc["description"]["purpose"]),
            "config": {"meta": {"contract": path, "owner": doc["team"]["name"], "read_by": sorted(readers[table])}},
        }
        for sla in doc.get("slaProperties", []):
            if sla["property"] == "latency":
                entry["config"]["loaded_at_field"] = sla["element"].rsplit(".", 1)[1]
                entry["config"]["freshness"] = {"error_after": {"count": sla["value"], "period": _PERIODS[sla["unit"]]}}
        entry["columns"] = [{"name": n, "data_type": _trino_type(t), **({"description": _text(d)} if d else {})} for n, t, d in columns]
        if identifier and recent:  # declared in lake.sql, never enforced by Iceberg: a mart would count a duplicate twice
            check = {"column_list": list(identifier), "row_condition": f"{recent[0]} >= current_timestamp - {_RECENT}"}
            entry["data_tests"] = [{"dbt_expectations.expect_compound_columns_to_be_unique": {"arguments": check}}]
        sources.setdefault(namespace, []).append(entry)
    doc = {
        "version": 2,
        "sources": [
            {"name": ns, "description": f"Lake namespace {ns}, through Trino's read-only catalog lake (ADR-044).", "database": "lake", "schema": ns, "tables": t}
            for ns, t in sources.items()
        ],
    }
    return _yaml(doc)


def _dbt_selectors(products: list[dict[str, Any]]) -> str:
    """Per domain with marts: its models, and the checks of every lake table they read."""
    reads: dict[str, set[str]] = {}
    for p in products:
        for mart in p.get("marts", []):
            reads.setdefault(fence(p["domain"]), set()).update(mart["reads"])
    selectors = [
        {
            "name": name,
            "description": f"Domain {name}: run as dbt_{name}, the only user that writes catalog {name}.",
            "definition": {"union": [{"method": "fqn", "value": name}, *[{"method": "source", "value": t} for t in sorted(reads[name])]]},
        }
        for name in sorted(reads)
    ]
    return _yaml({"selectors": selectors})


def render(root: Path) -> dict[str, str]:
    """Every generated file, path from `root` -> content. Assumes `validate(root)` is clean."""
    contracts = root / "contracts"
    domains = yaml.safe_load((contracts / "domains.yaml").read_text())["domains"]
    products = [yaml.safe_load(p.read_text()) for p in sorted(contracts.glob("*/*/product.yaml"))]
    tables: dict[str, Contract] = {}
    for path in sorted(contracts.glob(f"*/*/*{SUFFIX}")):
        doc = yaml.safe_load(path.read_text())
        props = {p["property"]: p["value"] for p in doc["customProperties"]}
        tables[doc["schema"][0]["physicalName"]] = (path.relative_to(root).as_posix(), doc, props)
    lake = ddl.parse(root / LAKE_SQL)
    home = {t: f"{p['domain']}/{p['name']}" for p in products for t in p["outputs"]}
    inline = sorted(t for t, (_, doc, _) in tables.items() if "properties" in doc["schema"][0])

    out = {RETENTION: json.dumps({t: c[2]["retention"] for t, c in tables.items()}, indent=2, sort_keys=True) + "\n"}
    out |= {f"{GENERATED_DDL}/{t}.sql": _table_ddl(*tables[t]) for t in inline}
    out[f"{GENERATED_DDL}/README.md"] = _ddl_readme(inline)
    out |= {f"{PAGES}/{p['domain']}/{p['name']}.md": _page(p, tables, lake, home) for p in products}
    out[f"{PAGES}/README.md"] = _index(domains, products)
    out[WAREHOUSES] = _warehouses(domains)
    out[TRINO_RULES] = _rules(domains)
    out |= {f"{CATALOGS}/{fence(d)}.properties": _catalog(d, spec, local=False) for d, spec in domains.items()}
    out |= {f"{TEST_CATALOGS}/{fence(d)}.properties": _catalog(d, spec, local=True) for d, spec in domains.items()}
    out[DBT_SOURCES] = _dbt_sources(products, tables, lake)
    out[DBT_SELECTORS] = _dbt_selectors(products)
    return out


def generate(root: Path) -> dict[str, str]:
    """Render, then replace the owned directories and retention.json. Returns what was written."""
    files = render(root)  # before deleting anything, so a render that raises leaves the tree as it was
    for owned in OWNED:
        shutil.rmtree(root / owned, ignore_errors=True)
    for shared in (CATALOGS, TEST_CATALOGS):  # directories with hand-written files too: only ours go
        for path in (root / shared).glob("*.properties"):
            if path.read_text().startswith(f"# {HEADER}"):
                path.unlink()
    for rel, text in sorted(files.items()):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text)
    return files


