"""k2gen generate and k2gen new: files written from the contracts (ADR-032).

`generate` runs only on a tree `validate` passes. It renders every output in
memory, deletes the directories it owns, then writes them again in sorted
order, so two runs are byte-identical and a deleted contract leaves nothing:

    docker/lake/ddl/generated/            DDL for contracts with inline columns (owned)
    docker/lake/generated/retention.json  snapshot expiry in days, per table
    docs/products/                        a page per product and the index (owned)

and, from contracts/domains.yaml, one fence per domain (ADR-044):

    docker/lake/generated/warehouses.txt  the Lakekeeper warehouses init-lake.sh creates
    docker/trino/etc/catalog/<fence>.properties   a writable Trino catalog per domain
    docker/trino/test/local/<fence>.properties    its twin on a local metastore, for make test-trino
    docker/trino/etc/rules.json           only a domain's writer changes its catalog with SQL statements

and, from each product's marts (dbt/README.md):

    dbt/models/_sources.yml               every lake table a mart reads: Trino column types, the
                                          uniqueness test on its identifier fields, its freshness
    dbt/selectors.yml                     one selector per domain with marts, run as its writer

A catalog file is the generator's if it starts with the generated header; those are
deleted and written again, so a removed domain takes its catalog with it, and the
hand-written `lake.properties` beside them is never touched.

`new` scaffolds contracts/<domain>/<name>/: a descriptor and one contract for a
table lake.sql does not create, so its columns are inline and `generate` writes
its DDL. The scaffold passes `validate` as written.
"""

