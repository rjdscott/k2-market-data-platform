{#- k2_test_results(): every builder's test results (dbt/macros/k2_results.sql), in one union, the
    model of model.QUALITY_RESULTS (ADR-046). Generated by k2gen from the release's products,
    model.test_results_writers: one branch per product, its <domain>.<fence>__base.dq_test_results
    read through the reader catalog at main, which Trino's rules let only that model's builder
    read. At dbt build or run, a branch whose table does not exist yet (the product has not built
    with a test) is left out rather than failing the build; parse, compile and docs render every
    branch and reach no warehouse. The first branch is empty and types the columns, so the model
    builds with no results anywhere. A branch keeps only its own builder's rows. -#}
{% macro k2_test_results() -%}
select cast(null as varchar) as "product_id", cast(null as varchar) as "run_id", cast(null as varchar) as "dbt_invocation_id", cast(null as varchar) as "release_id", cast(null as timestamp(6) with time zone) as "run_started_at", cast(null as varchar) as "writer", cast(null as varchar) as "unique_id", cast(null as varchar) as "test_name", cast(null as varchar) as "tested", cast(null as varchar) as "status", cast(null as bigint) as "failures", cast(null as double) as "execution_time", cast(null as varchar) as "message" where false
{%- if k2_test_results_exist('ops_insight', 'daily_load__base') %}
union all
select 'ops-insight.daily-load' as "product_id", "run_id", "dbt_invocation_id", "release_id", "run_started_at", "writer", "unique_id", "test_name", "tested", "status", "failures", "execution_time", "message" from "ops_insight"."daily_load__base"."dq_test_results" where "writer" = 'dbt_daily_load'
{%- endif %}
{%- if k2_test_results_exist('sensor_net', 'station_readings__base') %}
union all
select 'sensor-net.station-readings' as "product_id", "run_id", "dbt_invocation_id", "release_id", "run_started_at", "writer", "unique_id", "test_name", "tested", "status", "failures", "execution_time", "message" from "sensor_net"."station_readings__base"."dq_test_results" where "writer" = 'dbt_station_readings'
{%- endif %}
{%- endmacro %}

{% macro k2_test_results_exist(catalog, schema) -%}
  {{- return(not (execute and flags.WHICH in ('build', 'run'))
      or adapter.get_relation(database=catalog, schema=schema, identifier='dq_test_results') is not none) -}}
{%- endmacro %}
